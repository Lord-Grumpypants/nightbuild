#!/usr/bin/env python3
"""Prepare official REAPI protobuf sources for NightBuild's native target graph."""
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / "build" / "reapi"
SOURCE = WORK / "grpc"
GENERATED = ROOT / "src" / "remote" / "generated"
FRAGMENT = ROOT / "third_party" / "reapi.generated.BUILD.nb"
GRPC_TAG = "v1.85.0"
BREW = Path("/opt/homebrew")


def run(*args):
    print("REAPI ·", " ".join(map(str, args)), flush=True)
    subprocess.run(args, cwd=ROOT, check=True)


def write_manifest(sources):
    lines = [
        "# Generated by scripts/build_reapi.py. Do not edit by hand.",
        "",
        'static_library("nightbuild_reapi"):',
        '    toolchain_include = ["toolchains/CXX.json"]',
        "    sources = [",
    ]
    lines.extend(f'        "{path.relative_to(ROOT).as_posix()}",' for path in sources)
    lines.extend([
        "    ]",
        "    include_dirs = [",
        '        "src/remote/generated",',
        '        "/opt/homebrew/include",',
        "    ]",
        '    cxxflags = ["-std=c++17", "-O2", "-fPIC"]',
        '    deps = ["grpc"]',
        "",
    ])
    FRAGMENT.write_text("\n".join(lines))


def main():
    WORK.mkdir(parents=True, exist_ok=True)
    if not SOURCE.exists():
        run(
            "git", "clone", "--branch", GRPC_TAG, "--depth", "1",
            "--recurse-submodules", "--shallow-submodules",
            "https://github.com/grpc/grpc.git", str(SOURCE),
        )

    protoc = BREW / "opt" / "protobuf" / "bin" / "protoc"
    plugin = BREW / "opt" / "grpc" / "bin" / "grpc_cpp_plugin"
    if not protoc.is_file() or not plugin.is_file():
        raise SystemExit("error: install host generators with: brew install protobuf grpc")

    if GENERATED.exists():
        shutil.rmtree(GENERATED)

    run(
        sys.executable, str(ROOT / "scripts" / "generate_reapi.py"),
        str(protoc), str(plugin), str(BREW / "include"),
    )

    sources = sorted(
        path for path in GENERATED.rglob("*.pb.cc")
        if not path.name.endswith(".grpc.pb.cc")
    )
    sources += sorted(GENERATED.rglob("*.grpc.pb.cc"))
    if not sources:
        raise SystemExit("error: protoc generated no REAPI C++ sources")
    write_manifest(sources)
    print(f"REAPI · wrote NightBuild manifest for {len(sources)} generated translation units", flush=True)


if __name__ == "__main__":
    main()
